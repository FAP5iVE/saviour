// Builds the self-hosted vendor files from node_modules:
//   assets/vendor/vendor.js      GSAP + ScrollTrigger + SplitText + DrawSVG + Lenis (one ES module)
//   assets/vendor/VERSIONS.txt   exact versions that went into the bundle
//   assets/fonts/inter-latin-var.woff2   Inter variable font, Latin subset (from @fontsource-variable/inter)
//
// Run:  npm install  then  npm run vendor
// Commit the output: the live site needs these files and the host does not run esbuild.

import { build } from 'esbuild';
import { copyFile, mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nm = (...p) => path.join(root, 'node_modules', ...p);
const vendorDir = path.join(root, 'assets', 'vendor');
const fontsDir = path.join(root, 'assets', 'fonts');

function fail(message) {
  console.error(`\nvendor: ${message}\n`);
  process.exit(1);
}

async function pkgInfo(name) {
  const file = nm(...name.split('/'), 'package.json');
  if (!existsSync(file)) fail(`"${name}" is not installed. Run "npm install" first.`);
  const pkg = JSON.parse(await readFile(file, 'utf8'));
  return { name, version: pkg.version, license: pkg.license ?? 'see package' };
}

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;

// 1. Make sure everything we need is installed
const packages = await Promise.all(
  ['gsap', 'lenis', 'esbuild', '@fontsource-variable/inter'].map(pkgInfo),
);

// 2. Bundle GSAP + plugins + Lenis into one ES module
await mkdir(vendorDir, { recursive: true });
const outfile = path.join(vendorDir, 'vendor.js');
try {
  await build({
    entryPoints: [path.join(root, 'scripts', 'vendor-entry.mjs')],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    legalComments: 'eof',
    logLevel: 'warning',
  });
} catch (error) {
  fail(
    'esbuild could not build the bundle. Most likely an import in scripts/vendor-entry.mjs ' +
      `does not exist in the installed version.\n${error.message ?? error}`,
  );
}

// 3. Copy the Inter variable font (Latin subset)
await mkdir(fontsDir, { recursive: true });
const interFiles = nm('@fontsource-variable', 'inter', 'files');
let fontCopied = false;
if (existsSync(interFiles)) {
  const names = await readdir(interFiles);
  const match = names.find((n) => /^inter-latin-wght-normal\.woff2$/.test(n));
  if (match) {
    await copyFile(path.join(interFiles, match), path.join(fontsDir, 'inter-latin-var.woff2'));
    fontCopied = true;
  } else {
    console.warn(
      'vendor: could not find inter-latin-wght-normal.woff2. Files available:\n  ' +
        names
          .filter((n) => n.endsWith('.woff2'))
          .slice(0, 12)
          .join('\n  '),
    );
  }
}

// 4. Record versions
const lines = [
  'Self-hosted vendor files. Generated by "npm run vendor". Do not edit by hand.',
  `Built: ${new Date().toISOString()}`,
  '',
  ...packages.map((p) => `${p.name}@${p.version}  (${p.license})`),
  '',
  'GSAP: free under the GreenSock standard license (https://gsap.com/standard-license).',
  'Lenis: MIT.',
  'Inter: SIL Open Font License 1.1.',
];
await writeFile(path.join(vendorDir, 'VERSIONS.txt'), `${lines.join('\n')}\n`);

// 5. Report sizes (feeds the performance budget)
const raw = await readFile(outfile);
console.log('\nVendor build finished.');
packages.forEach((p) => console.log(`  ${p.name}@${p.version}`));
console.log(`  assets/vendor/vendor.js  ${kb(raw.length)} raw, ${kb(gzipSync(raw).length)} gzip`);
if (fontCopied) {
  const size = (await stat(path.join(fontsDir, 'inter-latin-var.woff2'))).size;
  console.log(`  assets/fonts/inter-latin-var.woff2  ${kb(size)}`);
}

// 6. Remind about the font that cannot come from npm
if (!existsSync(path.join(fontsDir, 'clash-display-600.woff2'))) {
  console.log(
    '\nStill needed by hand: assets/fonts/clash-display-600.woff2 ' +
      '(download from Fontshare, see assets/fonts/README.md).',
  );
}
